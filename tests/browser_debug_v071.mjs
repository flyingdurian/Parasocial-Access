import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
try{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(resolve('dist/index.html')).href);
 await page.getByRole('button',{name:/TEST MENU/}).click();
 assert.match(await page.locator('h1').innerText(),/DEVELOPER\s+ACCESS/);
 assert.match(await page.locator('.debug-world').first().innerText(),/1 \/ 5 levels accessible/);
 await page.getByRole('button',{name:'UNLOCK EVERY WORLD & CHAPTER'}).click();
 assert.match(await page.locator('.debug-world').nth(3).innerText(),/5 \/ 5 levels accessible/);
 await page.getByRole('button',{name:'ENTER CREATOR NETWORK'}).click();
 assert.equal(await page.locator('.network-event.locked').count(),0);
 await page.getByRole('button',{name:/TEST MENU/}).click();
 const initialCredits=await page.locator('.debug-status-line').innerText();
 assert.match(initialCredits,/CREDITS ◈ 0/);
 await page.getByRole('button',{name:/1,000 TEST CREDITS/}).click();
 assert.match(await page.locator('.debug-status-line').innerText(),/CREDITS ◈ 1,000/);
 await page.locator('.debug-transfer summary').click();
 const backup=await page.locator('#debug-export').inputValue();
 assert.ok(backup.includes('"feedfall-rush-save"'));
 await page.getByRole('button',{name:'DISABLE DEVELOPER UNLOCKS'}).click();
 assert.match(await page.locator('.debug-world').nth(3).innerText(),/1 \/ 5 levels accessible|0 \/ 5 levels accessible/);
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('.debug-transfer summary').click();
 await page.locator('#debug-import').fill(backup);
 await page.getByRole('button',{name:'IMPORT & REPLACE LOCAL SAVE'}).click();
 assert.match(await page.locator('.debug-world').nth(3).innerText(),/5 \/ 5 levels accessible/);
 await page.reload();
 await page.getByRole('button',{name:/TEST MENU/}).click();
 assert.match(await page.locator('.debug-status-line').innerText(),/CREDITS ◈ 1,000/);
 assert.deepEqual(errors,[]);
 console.log('v0.7.1 MOBILE BROWSER DEBUG GREEN: unlock all, creator chapters, credits, export/import, persistence, no page errors');
} finally {await browser.close();}
